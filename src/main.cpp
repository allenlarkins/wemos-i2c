// Menu tree, built as fixed static instances (no dynamic allocation).
extern Menu mainMenu;

MenuItem aboutMenuItems[] = {
  {"Version", nullptr},
  {"Build", nullptr},
};
Menu aboutMenu("About", aboutMenuItems, 2, &mainMenu);

MenuItem mainMenuItems[] = {
  {"Status", nullptr},
  {"Settings", nullptr},
  {"About", &aboutMenu},
};
Menu mainMenu("D1 mini menu", mainMenuItems, 3, nullptr);

Menu *activeMenu = &mainMenu;

int lastEncoderA = HIGH;
int lastSelect = HIGH;
int lastBack = HIGH;
unsigned long lastInputMs = 0;

// Forward declarations
bool inputReady();
EncoderMovement processRotaryEncoder();


void drawImage() {
  // 0x3C is default i2c adress in some cases MAY be different
  display.clearDisplay();
  display.setTextSize(2);
  display.setTextColor(SH110X_WHITE);
  display.drawBitmap(0, 0, oled_image, OLED_WIDTH, OLED_HEIGHT, SH110X_WHITE);
  display.display();
}


bool inputReady() {
  const unsigned long now = millis();
  if (now - lastInputMs < 35) return false;
  lastInputMs = now;
  return true;
}

void setup() {
  pinMode(ENC_ROT_PIN, INPUT_PULLUP);
  pinMode(ENC_ROT_DIR_PIN, INPUT_PULLUP);
  pinMode(SELECT_PIN, INPUT_PULLUP);
  pinMode(BACK_PIN, INPUT_PULLUP);
  lastEncoderA = digitalRead(ENC_ROT_PIN);

  Serial.begin(115200);  
  delay(50);              
  Serial.println(F("debug: boot menu"));

  Wire.begin(OLED_SDA, OLED_SCL);
  Wire.beginTransmission(OLED_ADDRESS);  
  const uint8_t oledAck = Wire.endTransmission();  
  Serial.print(F("debug: OLED 0x3C ACK="));  
  Serial.println(oledAck);  // 0 means the display answered.
  display.begin(OLED_ADDRESS, true);
  activeMenu->draw(display);
}

EncoderMovement processRotaryEncoder() {
  EncoderMovement l_encodeResult = EncoderMovement::None;
  const int rotated = digitalRead(ENC_ROT_PIN);
  if (rotated != lastEncoderA && rotated == LOW && inputReady()) {
    if (digitalRead(ENC_ROT_DIR_PIN) == HIGH) {
      l_encodeResult = EncoderMovement::Clockwise;
      Serial.println(F("debug: encoder turn - clockwise"));
    } else {
      l_encodeResult = EncoderMovement::AntiClockwise;
      Serial.println(F("debug: encoder turn - anti-clockwise"));
    }
    activeMenu->draw(display);
  }
  lastEncoderA = rotated;
  return l_encodeResult;
}

void loop() {

  //
  // Check the rotary encoder and buttons, and update the menu selection accordingly.
  //
  EncoderMovement l_rotaryMotion = processRotaryEncoder();
  if (l_rotaryMotion == EncoderMovement::Clockwise) {
    activeMenu->selectNext();
    activeMenu->draw(display);
  } else if (l_rotaryMotion == EncoderMovement::AntiClockwise) {
    activeMenu->selectPrevious();
    activeMenu->draw(display);
  }

  const int l_selectNow = digitalRead(SELECT_PIN);
  if (lastSelect == HIGH && l_selectNow == LOW && inputReady()) {
    Serial.println(F("schematik-debug: select press"));
    Menu *submenu = activeMenu->selectedSubmenu();
    if (submenu != nullptr) {
      activeMenu = submenu;
      activeMenu->draw(display);
    } else {
      activeMenu->drawSelection(display);
    }
  }
  lastSelect = l_selectNow;

  const int l_backNow = digitalRead(BACK_PIN);
  if (lastBack == HIGH && l_backNow == LOW && inputReady()) {
    Serial.println(F("schematik-debug: back press"));
    if (activeMenu->parent() != nullptr) {
      activeMenu = activeMenu->parent();
    }
    activeMenu->draw(display);
  }
  lastBack = l_backNow;
}